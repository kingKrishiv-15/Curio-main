#!/usr/bin/env python3
"""Build the single, repeatable SQL Editor installer from versioned migrations.

The CLI still uses the original ordered migration history. The generated file
is for projects configured through the dashboard, including interrupted setups.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'supabase/setup.sql'


def repeatable(sql: str) -> str:
    sql = re.sub(r'^create table (?!if not exists\b)', 'create table if not exists ', sql, flags=re.M | re.I)
    sql = re.sub(r'^create (unique )?index (?!if not exists\b)', lambda m: f'create {m[1] or ""}index if not exists ', sql, flags=re.M | re.I)
    sql = re.sub(r'^create function\b', 'create or replace function', sql, flags=re.M | re.I)
    sql = re.sub(r'^create policy ("[^"]+"|\w+) on ([\w.]+)',
                 lambda m: f'drop policy if exists {m[1]} on {m[2]};\n{m[0]}', sql, flags=re.M | re.I)
    sql = re.sub(r'^create trigger (\w+)\b([^;]*?\bon\s+)([\w.]+)',
                 lambda m: f'drop trigger if exists {m[1]} on {m[3]};\n{m[0]}', sql, flags=re.M | re.I)
    return sql


def render() -> str:
    parts = ["""-- GENERATED by python3 tool/build_supabase_setup.py. Do not edit by hand.
-- CURIO DATABASE SETUP: paste this ENTIRE file into Supabase SQL Editor and Run.
-- Works on a fresh project or a partially applied Curio schema. Repeatable.
-- Keeps existing accounts, learner names, XP, activities and discoveries.
-- Do not use seed_demo_account.sql or the dummy-data files for production.
begin;
select pg_advisory_xact_lock(hashtext('curio_database_setup'));
create schema if not exists extensions;
set local search_path = public, extensions;
"""]
    for path in sorted((ROOT / 'supabase/migrations').glob('*.sql')):
        parts.append(f'\n-- SOURCE: {path.name}\n' + repeatable(path.read_text()))
    parts.append("""
-- Backfill parents who signed up before the application schema was installed.
insert into public.profiles(id, display_name)
select id, coalesce(raw_user_meta_data ->> 'full_name', split_part(email, '@', 1))
from auth.users on conflict (id) do nothing;
insert into public.family_settings(parent_id)
select id from auth.users on conflict (parent_id) do nothing;

notify pgrst, 'reload schema';
commit;
select 'Curio database setup complete' as status;
""")
    return '\n'.join(parts)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('supabase/setup.sql is stale. Run python3 tool/build_supabase_setup.py')
        print('Supabase setup bundle is current.')
    else:
        OUTPUT.write_text(content)
        print('Generated supabase/setup.sql')
