// Builds everything Second Opinion needs from the authored days in days.js:
//
//   supabase/seed_second_opinion.sql              one daily_puzzles row per day
//   test/fixtures/second_opinion_days.json        the same days, for Dart tests
//   lib/features/games/second_opinion/data/demo_puzzle.dart   the demo puzzle
//
// Run: node tool/second_opinion/build.js
// It refuses to write anything if a day breaks a content rule.
const fs = require('fs'), path = require('path');
const { demo, days } = require('./days.js');
const root = path.join(__dirname, '..', '..');

const PROBES = {
  source: 'How do you know that?',
  current: 'Is that still true?',
  example: 'Give me a specific example.',
  counter: 'What is the strongest argument against this?',
  scope: 'Did you answer what I actually asked?',
  unsure: 'What are you unsure about here?',
};
const FLAWS = ['fabricated', 'confident_guess', 'out_of_date', 'scope_drift', 'cherry_picked'];
const BANNED = /\b(vaccin|medicine|medication|disease|cancer|diet|calorie|election|president|prime minister|parliament|war\b|religio|suicide|drug)/i;

function check(day, label) {
  const errors = [];
  const fail = m => errors.push(`${label}: ${m}`);
  const words = day.brief.trim().split(/\s+/).length;
  if (words < 150 || words > 250) fail(`brief is ${words} words, must be 150 to 250`);
  if (day.claims.length !== 8) fail(`has ${day.claims.length} claims, must be 8`);
  const flawed = Object.keys(day.flawed).map(Number);
  if (flawed.length !== 3) fail(`has ${flawed.length} flawed claims, must be 3`);
  for (const i of flawed) {
    const [type, probe, why] = day.flawed[i];
    if (!(i >= 0 && i < 8)) fail(`flawed index ${i} is out of range`);
    if (!FLAWS.includes(type)) fail(`unknown flaw type ${type}`);
    if (!PROBES[probe]) fail(`unknown probe ${probe}`);
    if (!why || why.length < 20) fail(`flawed claim ${i} needs a real explanation`);
  }
  const types = flawed.map(i => day.flawed[i][0]);
  if (new Set(types).size === 1) fail('uses the same failure type three times');
  const exposing = new Set(flawed.map(i => day.flawed[i][1]));
  if (exposing.size < 1 || exposing.size > 2) fail(`${exposing.size} probes expose errors, must be 1 or 2`);
  for (const id of Object.keys(PROBES)) if (!day.replies[id] || day.replies[id].length < 30) fail(`missing reply for ${id}`);
  const all = [day.topic, day.brief, ...day.claims, ...Object.values(day.replies), ...flawed.map(i => day.flawed[i][2])].join(' ');
  if (/[–—]/.test(all)) fail('contains an em dash or en dash');
  if (BANNED.test(all)) fail(`touches a banned subject (${all.match(BANNED)[0]})`);
  return errors;
}

function split(day, number) {
  const id = i => `c${i + 1}`;
  const exposes = {};
  const flawed = {};
  for (const [i, [type, probe, why]] of Object.entries(day.flawed)) {
    (exposes[probe] ||= []).push(id(+i));
    flawed[id(+i)] = { type, probe, why };
  }
  return {
    public: {
      number,
      topic: day.topic,
      brief: day.brief,
      seconds: 300,
      probes: Object.entries(PROBES).map(([pid, question]) => ({ id: pid, question })),
      claims: day.claims.map((text, i) => ({ id: id(i), text })),
    },
    answer: { replies: day.replies, exposes, flawed },
  };
}

const errors = [...check(demo, 'demo'), ...days.flatMap((d, i) => check(d, `day ${i + 1} (${d.topic})`))];
const topics = days.map(d => d.topic);
if (new Set(topics).size !== topics.length) errors.push('two days share a topic');
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

const built = days.map((d, i) => split(d, i + 1));
const q = s => "'" + s.replace(/'/g, "''") + "'";
const sql = `-- GENERATED by node tool/second_opinion/build.js from tool/second_opinion/days.js.
-- Do not edit by hand. Publishes ${built.length} days of Second Opinion, the first one
-- dated today, one per day after that. Safe to run again: existing dates are
-- left alone. Run it as the database owner (SQL Editor or supabase db execute).
do $seed$
declare
  v_key text;
  v_days jsonb := ${q(JSON.stringify(built))}::jsonb;
  v_day jsonb;
  v_index integer := 0;
begin
  select value into v_key from public.app_secrets where name = 'minigame_encryption_key';
  if v_key is null then
    raise exception 'minigame_encryption_key is not set in app_secrets';
  end if;
  for v_day in select * from jsonb_array_elements(v_days) loop
    insert into public.daily_puzzles (puzzle_date, puzzle_type, public_config, encrypted_answer, published_at)
    values (
      current_date + v_index,
      'second_opinion',
      v_day -> 'public',
      extensions.pgp_sym_encrypt((v_day -> 'answer')::text, v_key),
      now()
    )
    on conflict (puzzle_date, puzzle_type) do nothing;
    v_index := v_index + 1;
  end loop;
end
$seed$;
`;
fs.writeFileSync(path.join(root, 'supabase/seed_second_opinion.sql'), sql);
fs.mkdirSync(path.join(root, 'test/fixtures'), { recursive: true });
fs.writeFileSync(path.join(root, 'test/fixtures/second_opinion_days.json'), JSON.stringify(built, null, 1) + '\n');
const demoBuilt = split(demo, 0);
fs.mkdirSync(path.join(root, 'lib/features/games/second_opinion/data'), { recursive: true });
fs.writeFileSync(path.join(root, 'lib/features/games/second_opinion/data/demo_puzzle.dart'), `// GENERATED by node tool/second_opinion/build.js. Do not edit by hand.
//
// The one puzzle the app can play without a server (demo mode). It is not
// part of the daily schedule, so having its answers in the client gives
// nothing away about a real day.
const demoSecondOpinionJson = r'''
${JSON.stringify(demoBuilt, null, 1)}
''';
`);
console.log(`ok: ${built.length} days and the demo puzzle`);
